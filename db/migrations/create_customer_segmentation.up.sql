CREATE TABLE CPS_ROLES (
    ID            RAW(16) DEFAULT SYS_GUID() PRIMARY KEY,
    NAME          VARCHAR2(255),
    ROLE_CODE     VARCHAR2(100),
    DESCRIPTION   VARCHAR2(500),
    ENABLED       NUMBER(1) DEFAULT 1,
    IS_DELETED    NUMBER(1) DEFAULT 0,
    CREATED_AT    TIMESTAMP DEFAULT SYSTIMESTAMP,
    UPDATED_AT    TIMESTAMP,
    DELETED_AT    TIMESTAMP
);

CREATE TABLE CUSTOMER_SEGMENTATIONS (
    ID            RAW(16) DEFAULT SYS_GUID() PRIMARY KEY,
    ROLE_ID       RAW(16) NOT NULL,
    IS_ENABLED    NUMBER(1) DEFAULT 1,
    IS_DELETED    NUMBER(1) DEFAULT 0,
    CREATED_AT    TIMESTAMP DEFAULT SYSTIMESTAMP,
    UPDATED_AT    TIMESTAMP,

    CONSTRAINT FK_CUST_SEG_ROLE
        FOREIGN KEY (ROLE_ID)
        REFERENCES CPS_ROLES(ID)
        ON DELETE CASCADE
);

CREATE TABLE CUSTOMER_SUB_SEGMENTS (
    ID                RAW(16) DEFAULT SYS_GUID() PRIMARY KEY,
    CUSTOMER_SEG_ID   RAW(16) NOT NULL,
    NAME              VARCHAR2(255),
    CUSTOMER_GROUP    VARCHAR2(100),
    CUSTOMER_SEGMENT  VARCHAR2(100),

    CONSTRAINT FK_CUST_SUB_SEG
        FOREIGN KEY (CUSTOMER_SEG_ID)
        REFERENCES CUSTOMER_SEGMENTATIONS(ID)
        ON DELETE CASCADE
);
