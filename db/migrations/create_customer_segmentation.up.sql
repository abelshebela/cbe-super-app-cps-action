CREATE TABLE CUSTOMER_GROUPS (
    ID RAW(16) DEFAULT SYS_GUID() PRIMARY KEY,
    NAME VARCHAR2(32) NOT NULL,
    IS_ENABLED NUMBER(1) DEFAULT 1,
    IS_DELETED NUMBER(1) DEFAULT 0,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP,
    LAST_MODIFIED_AT TIMESTAMP DEFAULT SYSTIMESTAMP,
    DELETED_AT TIMESTAMP,
    CONSTRAINT CHK_CUSTOMER_GROUPS_IS_ENABLED CHECK (IS_ENABLED IN (0, 1)),
    CONSTRAINT CHK_CUSTOMER_GROUPS_IS_DELETED CHECK (IS_DELETED IN (0, 1))
);

CREATE TABLE SUPERAPP_ROLES (
    ID RAW(16) DEFAULT SYS_GUID() PRIMARY KEY,
    NAME VARCHAR2(32) NOT NULL,
    LABEL VARCHAR2(128),
    ROLE_CODE VARCHAR2(32) NOT NULL,
    DESCRIPTION VARCHAR2(128),
    IS_ENABLED NUMBER(1) DEFAULT 1,
    IS_DELETED NUMBER(1) DEFAULT 0,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP,
    LAST_MODIFIED_AT TIMESTAMP DEFAULT SYSTIMESTAMP,
    DELETED_AT TIMESTAMP,
    CONSTRAINT CHK_SUPERAPP_ROLE_IS_ENABLED CHECK (IS_ENABLED IN (0, 1)),
    CONSTRAINT CHK_SUPERAPP_ROLE_IS_DELETED CHECK (IS_DELETED IN (0, 1))
);


CREATE TABLE CUSTOMER_SEGMENTATIONS (
    ID RAW(16) DEFAULT SYS_GUID() PRIMARY KEY,
    NAME VARCHAR2(32) NOT NULL,
    CUSTOMER_GROUP_ID RAW(16) NOT NULL,
    IS_ENABLED NUMBER(1) DEFAULT 1,
    IS_DELETED NUMBER(1) DEFAULT 0,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP,
    LAST_MODIFIED_AT TIMESTAMP DEFAULT SYSTIMESTAMP,
    DELETED_AT TIMESTAMP,
    CONSTRAINT CHK_CUSTOMER_SEG_IS_ENABLED CHECK (IS_ENABLED IN (0, 1)),
    CONSTRAINT CHK_CUSTOMER_SEG_IS_DELETED CHECK (IS_DELETED IN (0, 1)),
    CONSTRAINT FK_CUSTOMER_SEGMENTATIONS_GROUP FOREIGN KEY (CUSTOMER_GROUP_ID) REFERENCES CUSTOMER_GROUPS (ID) ON DELETE CASCADE
);
CREATE INDEX IDX_CUSTOMER_SEGMENTATIONS_CUSTOMER_GROUP_ID ON CUSTOMER_SEGMENTATIONS(CUSTOMER_GROUP_ID);

CREATE TABLE CUSTOMER_SUB_SEGMENTS (
    ID RAW(16) DEFAULT SYS_GUID() PRIMARY KEY,
    NAME VARCHAR2(32) NOT NULL,
    CUSTOMER_SEGMENTATION_ID RAW(16) NOT NULL,
    SUPERAPP_ROLE_ID RAW(16) NOT NULL,
    IS_ENABLED NUMBER(1) DEFAULT 1,
    IS_DELETED NUMBER(1) DEFAULT 0,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP,
    LAST_MODIFIED_AT TIMESTAMP DEFAULT SYSTIMESTAMP,
    DELETED_AT TIMESTAMP,
    CONSTRAINT CHK_CUSTOMER_SUB_SEGMENTS_IS_ENABLED CHECK (IS_ENABLED IN (0, 1)),
    CONSTRAINT CHK_CUSTOMER_SUB_SEGMENTS_IS_DELETED CHECK (IS_DELETED IN (0, 1)),
    CONSTRAINT FK_CUSTOMER_SUB_SEGMENTS_CUSTOMER_SEGMENTATION_ID FOREIGN KEY (CUSTOMER_SEGMENTATION_ID) REFERENCES CUSTOMER_SEGMENTATIONS (ID) ON DELETE CASCADE,
    CONSTRAINT FK_CUSTOMER_SUB_SEGMENTS_SUPERAPP_ROLE_ID FOREIGN KEY (SUPERAPP_ROLE_ID) REFERENCES SUPERAPP_ROLE (ID) ON DELETE CASCADE
);
CREATE INDEX IDX_CUSTOMER_SUB_SEGMENTS_SUPERAPP_ROLE_ID ON CUSTOMER_SUB_SEGMENTS(SUPERAPP_ROLE_ID);
CREATE INDEX IDX_CUSTOMER_SUB_SEGMENTS_CUSTOMER_SEGMENTATION_ID ON CUSTOMER_SUB_SEGMENTS(CUSTOMER_SEGMENTATION_ID);