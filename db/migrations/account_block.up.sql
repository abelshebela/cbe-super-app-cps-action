CREATE TABLE ACCOUNT_BLOCKS (
    ID RAW(24) PRIMARY KEY,
    NAME VARCHAR2(255),
    CODE VARCHAR2(100) UNIQUE,
    ADDRESS VARCHAR2(500),
    PARENT_ID RAW(24),
    SLUG VARCHAR2(255),
    TYPE VARCHAR2(1), -- R, D, C, B
    IS_ENABLED NUMBER(1) DEFAULT 1,
    CITY_ID RAW(24),
    REGION_ID RAW(24),
    DISTRICT_ID RAW(24),
    IS_DELETED NUMBER(1) DEFAULT 0,
    CREATED_AT TIMESTAMP,
    UPDATED_AT TIMESTAMP,
    CONSTRAINT FK_ACCOUNT_BLOCK_PARENT FOREIGN KEY (CITY_ID) FOREIGN KEY (REGION_ID) FOREIGN KEY (DISTRICT_ID) REFERENCES ACCOUNT_BLOCKS (ID) ON DELETE CASCADE
);

