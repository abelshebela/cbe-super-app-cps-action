CREATE TABLE COMPANY (
    ID                  RAW(16)      DEFAULT SYS_GUID() NOT NULL,
    BRANCH_CODE         VARCHAR2(20) NOT NULL,
    BRANCH_NAME         VARCHAR2(128) NOT NULL,
    DISTRICT_NAME       VARCHAR2(64),
    REGION_NAME         VARCHAR2(32),
    FEDERAL_REGION_NAME VARCHAR2(64),
    DAO_CODE            NUMBER(10)   NOT NULL,
    ACCOUNT_TYPE        VARCHAR2(20) NOT NULL,
    IS_ENABLED          NUMBER(1)    DEFAULT 1 NOT NULL,
    CREATED_AT          TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL,
    LAST_MODIFIED_AT    TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT PK_COMPANY PRIMARY KEY (ID),
    CONSTRAINT UQ_COMPANY_BRANCH_CODE UNIQUE (BRANCH_CODE),
    CONSTRAINT UQ_COMPANY_DAO_CODE UNIQUE (DAO_CODE),
    CONSTRAINT CHK_COMPANY_IS_ENABLED CHECK (IS_ENABLED IN (0, 1)),
    CONSTRAINT CHK_COMPANY_ACCOUNT_TYPE CHECK (ACCOUNT_TYPE IN ('CONVENTIONAL', 'CBENOOR'))
);


CREATE TABLE ACCOUNT_BLOCKS_DISABLED_REASONS (
    ID RAW(16) DEFAULT SYS_GUID() PRIMARY KEY,
    COMPANY_ID RAW(16) NOT NULL,
    REASON_TEXT VARCHAR2(512),
    CREATED_BY VARCHAR2(128),
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP,
    LAST_MODIFIED_AT TIMESTAMP DEFAULT SYSTIMESTAMP,

    CONSTRAINT FK_ACCOUNT_BLOCKS_DISABLED_REASONS_COMPANY
        FOREIGN KEY (COMPANY_ID)
        REFERENCES COMPANY (ID)
        ON DELETE CASCADE
);